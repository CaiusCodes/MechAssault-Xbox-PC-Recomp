import hashlib, pathlib
R = pathlib.Path(__file__).resolve().parents[2]  # the repository
def blocks(p):
    x = p.read_bytes()
    return "".join(hashlib.sha1(x[i:i + 1024]).hexdigest()[:16] for i in range(0, len(x), 1024)), len(x)
rel = [("MechAssault (USA) (Rev 1)", "014624358ee6a930246748eebdcc6e174d769e93", R / "game_files/MechAssault (USA) (En,Fr,De) (Rev 1)/default.xbe"),
       ("MechAssault (USA, Europe), the original 2002 release", "919910b4f6fe5ba6b169754088dc61b89e77e2c9", R / "game_files/MechAssault (USA, Europe) (En,Fr,De)/default.xbe")]
out = ["// mechassault-recomp: generated by scratch, the supported releases' default.xbe as the copy check compares them:",
       "// the code fingerprint (gameimport::XbeCodeSha1), the size, and the first 8 bytes of each 1 KB block's SHA-1",
       '#include "common/check_copy.h"', "", "namespace mechassault {", "", "const KnownRelease kKnownReleases[] = {"]
for name, code, p in rel:
    b, n = blocks(p)
    out.append(f'    {{"{name}", "{code}", {n}u,')
    for i in range(0, len(b), 4000):
        out.append(f'     "{b[i:i + 4000]}"')
    out.append("    },")
out += ["};", "const size_t kKnownReleaseCount = sizeof(kKnownReleases) / sizeof(kKnownReleases[0]);", "", "}  // namespace mechassault", ""]
(R / "src/common/known_releases.cpp").write_text("\n".join(out), encoding="utf-8")
print("ok")
